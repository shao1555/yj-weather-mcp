namespace YjWeatherMcp;

/// <summary>Yahoo!天気の都道府県コード。北海道は 4 つの地方（1a〜1d）に分かれている。</summary>
public static class Prefectures
{
    public static readonly IReadOnlyList<(string Code, string Name)> All =
    [
        ("1a", "道北"), ("1b", "道央"), ("1c", "道東"), ("1d", "道南"),
        ("2", "青森県"), ("3", "岩手県"), ("4", "宮城県"), ("5", "秋田県"), ("6", "山形県"), ("7", "福島県"),
        ("8", "茨城県"), ("9", "栃木県"), ("10", "群馬県"), ("11", "埼玉県"), ("12", "千葉県"), ("13", "東京都"), ("14", "神奈川県"),
        ("15", "新潟県"), ("16", "富山県"), ("17", "石川県"), ("18", "福井県"), ("19", "山梨県"), ("20", "長野県"),
        ("21", "岐阜県"), ("22", "静岡県"), ("23", "愛知県"), ("24", "三重県"),
        ("25", "滋賀県"), ("26", "京都府"), ("27", "大阪府"), ("28", "兵庫県"), ("29", "奈良県"), ("30", "和歌山県"),
        ("31", "鳥取県"), ("32", "島根県"), ("33", "岡山県"), ("34", "広島県"), ("35", "山口県"),
        ("36", "徳島県"), ("37", "香川県"), ("38", "愛媛県"), ("39", "高知県"),
        ("40", "福岡県"), ("41", "佐賀県"), ("42", "長崎県"), ("43", "熊本県"), ("44", "大分県"), ("45", "宮崎県"), ("46", "鹿児島県"),
        ("47", "沖縄県"),
    ];

    /// <summary>「東京」「東京都」「13」「道央」などからコードを引く。見つからなければ null。</summary>
    public static (string Code, string Name)? Find(string query)
    {
        var q = query.Trim();
        foreach (var p in All)
        {
            if (p.Code.Equals(q, StringComparison.OrdinalIgnoreCase) || p.Name == q) return p;
        }
        // 「東京」「大阪」「京都」のように 都・府・県 を省いた指定。「京都」が「東京都」に当たらないよう部分一致にはしない
        foreach (var p in All)
        {
            if (p.Name.Length > 1 && p.Name[..^1] == q) return p;
        }
        return null;
    }
}
